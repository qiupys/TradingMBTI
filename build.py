def compact(rows):
    """定点复权：以真实首日收盘价为锚，用官方 pctChg 重构价格序列，消除除权除息假缺口。"""
    rows = [r for r in rows if r[4]]
    cum = [1.0]
    for r in rows[1:]:
        cum.append(cum[-1] * (1 + float(r[6]) / 100))
    c0 = float(rows[0][4])
    adj = [c0 * x for x in cum]
    factors = [adj[i] / float(r[4]) for i, r in enumerate(rows)]
    d, o, h, l, c, pct, v = [], [], [], [], [], [], []
    for i, r in enumerate(rows):
        f = factors[i]
        d.append(r[0]); o.append(round(float(r[1]) * f, 2)); h.append(round(float(r[2]) * f, 2))
        l.append(round(float(r[3]) * f, 2)); c.append(round(adj[i], 2)); pct.append(round(float(r[6]), 2))
        v.append(int(float(r[5] or 0)))   # 成交量（股），复权不影响量
    return {"dates": d, "o": o, "h": h, "l": l, "c": c, "pct": pct, "v": v}


