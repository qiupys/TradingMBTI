def enrich(s):
    """在『手写报道+行情快报』之外补充三类信息：大V观点（带情绪倾向）、国际视野（时代背景）、
    场外杂谈（与标的无关的噪音）。用股票代码做随机种子，保证每次构建结果一致。"""
    rng = random.Random(s["code"])
    dates = s["k"]["dates"]
    if not dates:
        return []
    name = s["name"]
    out = []

    def date_in(year=None):
        for _ in range(20):
            d = dates[rng.randrange(len(dates))]
            if year is None or int(d[:4]) == year:
                return d
        return dates[rng.randrange(len(dates))]

    # 大V观点：2–4 条，多空情绪随机
    for _ in range(rng.randint(2, 4)):
        pool = rng.random()
        tmpl = rng.choice(V_BULL if pool < 0.4 else V_BEAR if pool < 0.8 else V_FLAT)
        h = rng.choice(V_HANDLES)
        out.append([date_in(), f"大V观点 | {h}：" + tmpl.format(n=name)])
    # 国际视野：2–3 条，取窗口年份的真实国际事件
    y0, y1 = int(dates[0][:4]), int(dates[-1][:4])
    years = [y for y in range(y0, y1 + 1) if y in INTL_NEWS] or [max(y for y in INTL_NEWS if y <= y0)]
    pool = [t for y in years for t in INTL_NEWS[y]]
    rng.shuffle(pool)
    for t in pool[:rng.randint(2, 3)]:
        out.append([date_in(years[0] if any(int(d[:4]) == years[0] for d in dates) else None), "国际视野 | " + t])
    # 场外杂谈：2–3 条纯噪音
    for t in rng.sample(NOISE, rng.randint(2, 3)):
        out.append([date_in(), "场外杂谈 | " + t])
    return out


for s in SCEN:
    w0, w1 = s["w"]
    # 整条序列一起定点复权（锚定首日真实收盘），再在窗口起点切分：
    # lb = 入场前约一个月K线（仅展示判断用，不可交易），k = 可交易窗口
    full = compact([r for r in raw[s["code"]] if r[0] <= w1])
    i0 = next(i for i, d in enumerate(full["dates"]) if d >= w0)
    lb_n = min(22, i0)   # 中芯国际上市次日开局，lookback 天然只有 1-2 天
    s["lb"] = {kk: full[kk][i0 - lb_n:i0] for kk in ("dates", "o", "h", "l", "c")}
    s["k"] = {kk: full[kk][i0:] for kk in ("dates", "o", "h", "l", "c", "pct", "v")}
    # 资讯 = 手写还原报道 + 自动行情快报 + 大V观点/国际视野/场外杂谈扩充
    # （去重：同一日期最多保留 3 条，手写报道优先级最高）
    merged = sorted(s["news"] + auto_events(s["k"]) + enrich(s), key=lambda r: r[0])
    by_date = {}
    dedup = []
    prio = {"行情快报": 1, "大V观点": 2, "国际视野": 2, "场外杂谈": 3}
    for d, t in merged:
        tag = next((v for k, v in prio.items() if t.startswith(k)), 0)
        by_date.setdefault(d, 0)
        if by_date[d] >= 3: continue
        if by_date[d] >= 2 and tag >= 2: continue   # 后两天满时优先保留快报/手写
        by_date[d] += 1
        dedup.append([d, t])
    s["news"] = dedup
    s["period"] = w0.replace("-", ".") + " – " + w1.replace("-", ".")
    k = s["k"]
    print(f'{s["code"]} {s["name"]:5s} {len(k["c"]):3d}天(lb {lb_n}) {k["dates"][0]}→{k["dates"][-1]} '
          f'收盘 {k["c"][0]}→{k["c"][-1]} 峰值 {max(k["h"])} 资讯 {len(s["news"])}条')
