def auto_events(k, cap=8):
    """从真实行情自动生成『行情快报』：大波动日、20日新高/新低，最小间隔 4 个交易日。"""
    c, pct, dates = k["c"], k["pct"], k["dates"]
    cand = []
    for i in range(len(c)):
        p = pct[i]
        txts, sc = [], 0.0
        if abs(p) >= 4.5:
            txts.append(f"单日{'暴涨' if p > 0 else '暴跌'} {abs(p):.1f}%"); sc = abs(p)
        elif abs(p) >= 3.2:
            txts.append(f"单日{'大涨' if p > 0 else '大跌'} {abs(p):.1f}%"); sc = abs(p) - 1.5
        if i >= 20:
            w = c[i - 20:i]
            if p >= 2 and c[i] > max(w): txts.append("创20日新高"); sc += 2.5
            elif p <= -2 and c[i] < min(w): txts.append("创20日新低"); sc += 2.5
        if txts:
            cand.append((sc, i, dates[i], "，".join(txts)))
    cand.sort(key=lambda x: -x[0])          # 按重要性贪心挑选
    chosen = []
    for sc, i, d, t in cand:
        if all(abs(i - j) >= 4 for _, j, _, _ in chosen):
            chosen.append((sc, i, d, t))
            if len(chosen) >= cap: break
    chosen.sort(key=lambda x: x[1])         # 按日期排序输出
    return [[d, "行情快报 | " + t] for _, _, d, t in chosen]


