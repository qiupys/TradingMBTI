lg = bs.login()
out = {}
for code, start, end in POOL:
    rs = bs.query_history_k_data_plus(
        code, "date,open,high,low,close,volume,pctChg",
        start_date=start, end_date=end, frequency="d", adjustflag="3",
    )
    rows = []
    while (rs.error_code == '0') and rs.next():
        rows.append(rs.get_row_data())
    out[code] = rows
    closes = [float(r[4]) for r in rows if r[4]]
    dates = [r[0] for r in rows if r[4]]
    pcts = [float(r[6]) for r in rows if r[4] and r[6]]
    hi_i = closes.index(max(closes)); lo_i = closes.index(min(closes))
    mean = sum(pcts)/len(pcts)
    vol = (sum((p-mean)**2 for p in pcts)/len(pcts)) ** 0.5
    print(f"{code}: {len(rows)}天 {dates[0]}→{dates[-1]} | 收盘 {closes[0]}→{closes[-1]} | "
          f"最高 {max(closes):.2f}@{dates[hi_i]} 最低 {min(closes):.2f}@{dates[lo_i]} | "
          f"日波动 {vol:.2f}%")
